"""Semi-Synthetic Concept Drift Dataset implementation (Shaker Protocol)."""

from typing import Any
import pandas as pd
from .base import BaseDataset
from .drift_blending import DriftBlender
from .feature_matching import FeatureMatcher


class SemiSyntheticDriftDataset(BaseDataset):
    """
    Semi-synthetic concept drift dataset generated by splicing two empirical datasets.

    Adheres strictly to the Shaker Protocol (Shaker & Hüllermeier, 2015), providing
    feature alignment, controlled drift schedules, ground-truth change-point annotations,
    and drifting feature diagnostics.
    """

    def __init__(
        self,
        name: str = "semi_synthetic",
        display_name: str | None = None,
        X_a: pd.DataFrame | None = None,
        y_a: pd.Series | None = None,
        X_b: pd.DataFrame | None = None,
        y_b: pd.Series | None = None,
        match_strategy: str = "exact",
        manual_mapping: dict[str, str] | None = None,
        align_distributions: bool = False,
        scaler_type: str | None = "standard",
        scaler_mode: str = "joint",
        schedule: str = "gradual",
        n_samples: int | None = None,
        t_0: int | None = None,
        drift_width: int = 200,
        period: int = 500,
        random_seed: int = 42,
        static_file_path: str | None = None,
        target_column: str = "target",
    ) -> None:
        """
        Initialize SemiSyntheticDriftDataset.

        Parameters
        ----------
        name : str
            Unique dataset identifier.
        display_name : str | None
            Human-readable display name.
        X_a : pd.DataFrame | None
            Feature matrix for concept A.
        y_a : pd.Series | None
            Target series for concept A.
        X_b : pd.DataFrame | None
            Feature matrix for concept B.
        y_b : pd.Series | None
            Target series for concept B.
        match_strategy : str, default="exact"
            Feature matching strategy ("exact", "manual", "statistical", "subspace").
        manual_mapping : dict[str, str] | None
            Manual column mapping dict for "manual" strategy.
        align_distributions : bool, default=False
            Whether to normalize feature distributions.
        scaler_type : str | None, default="standard"
            Scaler type ("standard" or "minmax").
        scaler_mode : str, default="joint"
            Normalization mode ("joint" or "per_concept").
        schedule : str, default="gradual"
            Drift schedule ("abrupt", "gradual", "incremental", "recurring").
        n_samples : int | None, default=None
            Total stream length in samples.
        t_0 : int | None, default=None
            Drift inflection point / midpoint.
        drift_width : int, default=200
            Transition window width.
        period : int, default=500
            Period T for recurring drift.
        random_seed : int, default=42
            Random seed for reproducibility.
        static_file_path : str | None
            Path to static pre-generated CSV if loading from persistent cache.
        target_column : str, default="target"
            Target column name if loading from static CSV.
        """
        self._name = name
        self._display_name = display_name or f"Semi-Synthetic: {name}"

        self.X_a = X_a
        self.y_a = y_a
        self.X_b = X_b
        self.y_b = y_b

        self.match_strategy = match_strategy
        self.manual_mapping = manual_mapping
        self.align_distributions = align_distributions
        self.scaler_type = scaler_type
        self.scaler_mode = scaler_mode
        self.schedule = schedule
        self.n_samples = n_samples
        self.t_0 = t_0
        self.drift_width = drift_width
        self.period = period
        self.random_seed = random_seed
        self.static_file_path = static_file_path
        self.target_column = target_column

        # Ground truth state
        self._ground_truth_drift_points: list[int] = []
        self._drift_intervals: list[tuple[int, int]] = []
        self._concept_stream: pd.Series = pd.Series(dtype=int)
        self._drifting_features: list[str] = []
        self._feature_mapping: dict[str, str] = {}
        self._drift_diagnostics: pd.DataFrame = pd.DataFrame()

    @property
    def name(self) -> str:
        return self._name

    @property
    def display_name(self) -> str:
        return self._display_name

    @property
    def ground_truth_drift_points(self) -> list[int]:
        """Timestamps of ground-truth drift midpoints / inflection points."""
        return self._ground_truth_drift_points

    @property
    def drift_intervals(self) -> list[tuple[int, int]]:
        """Interval ranges [start, end] of concept transition regions."""
        return self._drift_intervals

    @property
    def concept_stream(self) -> pd.Series:
        """Stream array tracking the true generative source concept (0 for A, 1 for B)."""
        return self._concept_stream

    @property
    def drifting_features(self) -> list[str]:
        """Features with significant distribution drift between concepts."""
        return self._drifting_features

    @property
    def feature_mapping(self) -> dict[str, str]:
        """Mapping dictionary between Concept A and Concept B features."""
        return self._feature_mapping

    @property
    def drift_diagnostics(self) -> pd.DataFrame:
        """Full statistical diagnostics table for all aligned features."""
        return self._drift_diagnostics

    def get_params(self) -> dict[str, Any]:
        """Return parameters for the semi-synthetic dataset."""
        return {
            "match_strategy": self.match_strategy,
            "align_distributions": self.align_distributions,
            "scaler_type": self.scaler_type,
            "scaler_mode": self.scaler_mode,
            "schedule": self.schedule,
            "n_samples": self.n_samples,
            "t_0": self.t_0,
            "drift_width": self.drift_width,
            "period": self.period,
            "random_seed": self.random_seed,
        }

    def generate(self, **kwargs) -> tuple[pd.DataFrame, pd.Series]:
        """
        Generate or load the semi-synthetic concept drift stream.

        Returns
        -------
        tuple[pd.DataFrame, pd.Series]
            (X, y) stream tuple.
        """
        # If pre-saved static CSV file is available and concepts are not supplied directly
        if self.static_file_path is not None and (self.X_a is None or self.X_b is None):
            df = pd.read_csv(self.static_file_path)
            target_col = kwargs.get("target_column", self.target_column)

            if target_col in df.columns:
                y = df[target_col]
                drop_cols = [target_col]
            else:
                y = df.iloc[:, -1]
                drop_cols = [df.columns[-1]]

            if "_concept" in df.columns:
                self._concept_stream = df["_concept"]
                drop_cols.append("_concept")

            X = df.drop(columns=[c for c in drop_cols if c in df.columns])
            return X, y

        if self.X_a is None or self.y_a is None or self.X_b is None or self.y_b is None:
            raise ValueError("Source concepts (X_a, y_a, X_b, y_b) must be provided to generate stream.")

        # Merge runtime overrides
        match_strat = kwargs.get("match_strategy", self.match_strategy)
        manual_map = kwargs.get("manual_mapping", self.manual_mapping)
        align_dist = kwargs.get("align_distributions", self.align_distributions)
        scaler_t = kwargs.get("scaler_type", self.scaler_type)
        scaler_m = kwargs.get("scaler_mode", self.scaler_mode)
        sched = kwargs.get("schedule", self.schedule)
        n_samp = kwargs.get("n_samples", self.n_samples)
        t_zero = kwargs.get("t_0", self.t_0)
        width = kwargs.get("drift_width", self.drift_width)
        per = kwargs.get("period", self.period)
        seed = kwargs.get("random_seed", self.random_seed)

        # 1. Feature Alignment
        matcher = FeatureMatcher(
            match_strategy=match_strat,
            manual_mapping=manual_map,
            align_distributions=align_dist,
            scaler_type=scaler_t,
            scaler_mode=scaler_m,
            random_state=seed,
        )
        alignment_result = matcher.align(self.X_a, self.X_b)

        self._feature_mapping = alignment_result.feature_mapping
        self._drifting_features = alignment_result.drifting_features
        self._drift_diagnostics = alignment_result.drift_diagnostics

        # 2. Stream Blending
        blender = DriftBlender(
            schedule=sched,
            n_samples=n_samp,
            t_0=t_zero,
            w=width,
            period=per,
            random_state=seed,
        )
        blend_result = blender.blend(
            alignment_result.X_a_aligned,
            self.y_a,
            alignment_result.X_b_aligned,
            self.y_b,
        )

        self._ground_truth_drift_points = blend_result.ground_truth_drift_points
        self._drift_intervals = blend_result.drift_intervals
        self._concept_stream = blend_result.concept_stream

        return blend_result.X, blend_result.y

    @classmethod
    def from_registry_info(cls, name: str, registry_info: dict, registry: Any) -> "SemiSyntheticDriftDataset":
        """
        Instantiate SemiSyntheticDriftDataset from DatasetRegistry configuration.

        Parameters
        ----------
        name : str
            Dataset name.
        registry_info : dict
            Registry metadata dictionary.
        registry : DatasetRegistry
            Registry instance.

        Returns
        -------
        SemiSyntheticDriftDataset
            Configured dataset instance.
        """
        recipe = registry_info.get("recipe", {})
        csv_path = registry.get_dataset_path(name)

        ds = cls(
            name=name,
            display_name=registry_info.get("display_name", f"{name} (Semi-Synthetic)"),
            match_strategy=recipe.get("match_strategy", "exact"),
            manual_mapping=recipe.get("manual_mapping"),
            align_distributions=recipe.get("align_distributions", False),
            scaler_type=recipe.get("scaler_type", "standard"),
            scaler_mode=recipe.get("scaler_mode", "joint"),
            schedule=recipe.get("schedule", "gradual"),
            n_samples=recipe.get("n_samples"),
            t_0=recipe.get("t_0"),
            drift_width=recipe.get("drift_width", 200),
            period=recipe.get("period", 500),
            random_seed=recipe.get("random_seed", 42),
            static_file_path=csv_path,
            target_column=registry_info.get("target_column", "target"),
        )

        # Restore stored ground-truth metadata
        ds._ground_truth_drift_points = recipe.get("ground_truth_drift_points", [])
        raw_intervals = recipe.get("drift_intervals", [])
        ds._drift_intervals = [tuple(inv) for inv in raw_intervals]
        ds._drifting_features = recipe.get("drifting_features", [])
        ds._feature_mapping = recipe.get("feature_mapping", {})

        return ds
